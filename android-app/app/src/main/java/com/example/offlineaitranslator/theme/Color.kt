/**
 * Vendored COUI (ColorOS 17) colour tokens.
 *
 * Source: https://github.com/suqi8/coui — `theme/Colors.kt` (Apache-2.0). Values are the upstream
 * `lightColorScheme()` / `darkColorScheme()` defaults, including the state-layer slots (`press`,
 * `hover`, `focus`), the secondary-button fills and the press/state backgrounds that COUI 17 uses
 * for its touch motion. Slot names are kept identical to COUI so a future migration to the published
 * artifact is a mechanical import change.
 */
