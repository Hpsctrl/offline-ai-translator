data class CoUiColors(
    val primary: Color,
    val onPrimary: Color,
    val error: Color,
    val onError: Color,
    val disabledOnPrimaryButton: Color,
    val secondaryVariant: Color,
    val secondary: Color,
    val surfaceContainerHighest: Color,
    val outline: Color,
    val backgroundTop: Color,
    val primaryTextOnPopup: Color,
    val success: Color,
    val warning: Color,
    val errorTextBg: Color,
    val primaryText: Color,
    val labelTheme: Color,
    val link: Color,
    val disable: Color,
    val containerTheme: Color,
    val containerThemeHalftone: Color,
    val background: Color,
    val surface: Color,
    val backgroundElevated: Color,
    val backgroundElevatedWithCard: Color,
    val backgroundWithCard: Color,
    val surfaceTop: Color,
    val surfaceWithCard: Color,
    val bar: Color,
    val bottomBar: Color,
    val card: Color,
    val cardBackground: Color,
    val cardPressed: Color,
    val labelPrimary: Color,
    val labelPrimaryVariant: Color,
    val labelSecondary: Color,
    val labelSecondaryVariant: Color,
    val labelTertiary: Color,
    val labelQuaternary: Color,
    val labelOnColor: Color,
    val disabledNeutral: Color,
    val hintNeutral: Color,
    val container4: Color,
    val container8: Color,
    val container12: Color,
    val container16: Color,
    val containerSolid: Color,
    val fillSolid: Color,
    val divider: Color,
    val mask: Color,
    val neutralButton: Color,
    val red: Color,
    val green: Color,
    val blue: Color,
    val violet: Color,
    val isDark: Boolean,

    // COUI 17 state layers and component fills.
    val press: Color,
    val hover: Color,
    val focus: Color,
    val pressBackground: Color,
    val ripplePressBackground: Color,
    val secondaryButton: Color,
    val disabledSecondaryButton: Color,
    val disabledOnSecondaryButton: Color,
    val dialogButton: Color,
    val sliderBackground: Color,
    val disabledProgress: Color,
    val disabledProgressBackground: Color,
    val disabledTextFieldBorder: Color,
    val quarternaryNeutral: Color,
    val focusOutline: Color,
    val redVariant: Color,
    val greenVariant: Color,
    val blueVariant: Color,
    val violetVariant: Color,
    val orange: Color,
    val yellow: Color,
    val mint: Color,
    val cyan: Color,
    val azure: Color,
)

